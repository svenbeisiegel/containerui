// Package runtime defines the backend-neutral container runtime abstraction.
// The web UI only talks to the Runtime interface; concrete drivers (the
// wslc/docker/podman CLI driver, fake) live in sub-packages and register
// themselves via Register.
package runtime

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"strings"
	"time"
)

// Runtime is implemented by every container runtime driver.
type Runtime interface {
	Name() string
	Capabilities() Capabilities
	Info(ctx context.Context) (Info, error)

	ListContainers(ctx context.Context, opts ListContainersOpts) ([]Container, error)
	InspectContainer(ctx context.Context, id string) (json.RawMessage, error)
	CreateContainer(ctx context.Context, opts CreateContainerOpts) (string, error)
	StartContainer(ctx context.Context, id string) error
	StopContainer(ctx context.Context, id string, timeout *time.Duration) error
	RestartContainer(ctx context.Context, id string, timeout *time.Duration) error
	RemoveContainer(ctx context.Context, id string, force bool) error

	// CheckTerminal reports whether an interactive shell can be opened in
	// a running container and returns the shell to use.
	CheckTerminal(ctx context.Context, id string) (shell string, err error)
	// OpenTerminal starts opts.Shell in the container on a pseudo terminal.
	// The terminal lives until it is closed or the shell exits; ctx only
	// bounds starting it.
	OpenTerminal(ctx context.Context, id string, opts TerminalOpts) (Terminal, error)

	// ContainerLogs writes the container's output (stdout and stderr) to w.
	// With opts.Follow it keeps streaming until ctx ends or the container
	// stops.
	ContainerLogs(ctx context.Context, id string, opts LogsOpts, w io.Writer) error

	ListImages(ctx context.Context) ([]Image, error)
	PullImage(ctx context.Context, ref string, progress func(line string)) error
	RemoveImage(ctx context.Context, ref string, force bool) error
	TagImage(ctx context.Context, source, target string) error
	// InspectImage returns the runtime's raw inspect document for an image.
	InspectImage(ctx context.Context, ref string) (json.RawMessage, error)

	ListVolumes(ctx context.Context) ([]Volume, error)
	InspectVolume(ctx context.Context, name string) (json.RawMessage, error)
	// CreateVolume creates a volume and returns its name (generated by the
	// runtime if opts.Name is empty).
	CreateVolume(ctx context.Context, opts CreateVolumeOpts) (string, error)
	// RemoveVolume deletes a volume. force only suppresses the error for a
	// missing volume; a volume in use by a container is never removed.
	RemoveVolume(ctx context.Context, name string, force bool) error
	// PruneVolumes removes unused anonymous volumes, with all also unused
	// named volumes, and returns the runtime's report.
	PruneVolumes(ctx context.Context, all bool) (string, error)

	ListNetworks(ctx context.Context) ([]Network, error)
	InspectNetwork(ctx context.Context, name string) (json.RawMessage, error)
	// CreateNetwork creates a network and returns its ID (or name).
	CreateNetwork(ctx context.Context, opts CreateNetworkOpts) (string, error)
	// RemoveNetwork deletes a network; one with connected containers is
	// never removed.
	RemoveNetwork(ctx context.Context, name string) error
	// PruneNetworks removes all unused custom networks and returns the
	// runtime's report.
	PruneNetworks(ctx context.Context) (string, error)
	ConnectNetwork(ctx context.Context, network, container string, opts ConnectNetworkOpts) error
	DisconnectNetwork(ctx context.Context, network, container string) error
}

// Capabilities tells the UI which optional features a driver supports, so
// unsupported actions can be hidden instead of failing.
type Capabilities struct {
	Restart  bool
	Inspect  bool
	Pull     bool
	Tag      bool
	Volumes  bool
	Networks bool
	Terminal bool // interactive shell in running containers
	Logs     bool // container output (download and follow)

	// VolumeDrivers lists the volume drivers CreateVolume accepts; the
	// first is the runtime's default.
	VolumeDrivers []string
	// PruneAnonymous: PruneVolumes(all=false) can remove only anonymous
	// volumes. Without it, prune always removes all unused volumes.
	PruneAnonymous bool

	// NetworkDrivers lists the drivers CreateNetwork accepts; the first is
	// the runtime's default.
	NetworkDrivers []string
	// NetworkIPv6: CreateNetwork can create IPv6 (dual-stack) networks.
	NetworkIPv6 bool

	// Compose: the driver implements Composer and a compose tool was found.
	Compose bool
	// ComposeVersion describes the compose tool, e.g. "docker compose 2.29.1".
	ComposeVersion string
}

// LogsOpts selects which part of a container's output ContainerLogs writes.
type LogsOpts struct {
	Follow bool // keep streaming new output
	Tail   int  // only the last Tail lines; 0 means all
}

type Info struct {
	Driver  string
	Version string
}

type ListContainersOpts struct {
	All bool // include stopped containers
}

type State string

const (
	StateCreated    State = "created"
	StateRunning    State = "running"
	StatePaused     State = "paused"
	StateRestarting State = "restarting"
	StateRemoving   State = "removing"
	StateExited     State = "exited"
	StateDead       State = "dead"
	StateUnknown    State = "unknown"
)

// ParseState normalizes a runtime-reported state string.
func ParseState(s string) State {
	switch st := State(s); st {
	case StateCreated, StateRunning, StatePaused, StateRestarting, StateRemoving, StateExited, StateDead:
		return st
	case "stopped":
		return StateExited
	}
	return StateUnknown
}

func (s State) IsRunning() bool { return s == StateRunning || s == StateRestarting }

type PortMapping struct {
	HostIP        string
	HostPort      uint16
	ContainerPort uint16
	Protocol      string // tcp or udp
}

func (p PortMapping) String() string {
	proto := p.Protocol
	if proto == "" {
		proto = "tcp"
	}
	if p.HostPort == 0 {
		return fmt.Sprintf("%d/%s", p.ContainerPort, proto)
	}
	if p.HostIP != "" {
		return fmt.Sprintf("%s:%d->%d/%s", p.HostIP, p.HostPort, p.ContainerPort, proto)
	}
	return fmt.Sprintf("%d->%d/%s", p.HostPort, p.ContainerPort, proto)
}

type Container struct {
	ID         string
	Name       string
	Image      string
	Command    string
	State      State
	Status     string // human-readable, e.g. "Up 4 hours"
	Ports      string // human-readable port summary
	Networks   []string
	Mounts     []string
	Created    time.Time
	RunningFor string
	Labels     map[string]string
}

type Image struct {
	ID         string
	Repository string
	Tag        string
	Digest     string
	Size       string // human-readable as reported by the runtime
	Created    time.Time
	Containers int
}

// Ref returns the most specific reference usable to address the image.
func (i Image) Ref() string {
	if i.Repository == "" || i.Repository == "<none>" {
		return i.ID
	}
	if i.Tag == "" || i.Tag == "<none>" {
		return i.Repository
	}
	return i.Repository + ":" + i.Tag
}

// SplitRef splits "registry:5000/repo:tag" into repository and tag. The tag
// defaults to "latest"; a digest reference (repo@sha256:...) has no tag.
func SplitRef(ref string) (repo, tag string) {
	if i := strings.Index(ref, "@"); i >= 0 {
		return ref[:i], ""
	}
	if i := strings.LastIndex(ref, ":"); i > strings.LastIndex(ref, "/") {
		return ref[:i], ref[i+1:]
	}
	return ref, "latest"
}

type Volume struct {
	Name       string
	Driver     string
	Mountpoint string
	Scope      string
	Labels     map[string]string
}

type Network struct {
	ID       string
	Name     string
	Driver   string
	Scope    string
	Internal bool
	IPv6     bool
	Created  time.Time
	Labels   map[string]string
}

// Sentinel errors drivers wrap so the UI can react uniformly.
var (
	ErrNotFound    = errors.New("not found")
	ErrConflict    = errors.New("conflict")
	ErrUnsupported = errors.New("not supported by this runtime")
	ErrInvalid     = errors.New("invalid argument")
)

// CommandError describes a failed backend command (CLI invocation, API call).
type CommandError struct {
	Op       string // e.g. "container stop"
	Code     string // backend error code, e.g. WSLC_E_CONTAINER_NOT_FOUND
	ExitCode int
	Output   string // stderr / message from the backend
	Kind     error  // one of the sentinel errors, or nil
}

func (e *CommandError) Error() string {
	msg := e.Op + " failed"
	if e.Code != "" {
		msg += " (" + e.Code + ")"
	} else if e.ExitCode != 0 {
		msg += fmt.Sprintf(" (exit code %d)", e.ExitCode)
	}
	if e.Output != "" {
		msg += ": " + e.Output
	}
	return msg
}

func (e *CommandError) Unwrap() error { return e.Kind }
